# =======================

def menu():
    sistema = SistemaTurnos()

    # Médicos precargados
    sistema.agregar_medico(Medico("Dr. Pérez"))
    sistema.agregar_medico(Medico("Dra. Gómez"))

    while True:
        print("\n--- SISTEMA DE TURNOS ---")
        print("1. Listar médicos")
        print("2. Registrar turno")
        print("3. Mostrar turnos")
        print("0. Salir")

        op = input("Opción: ")

        if op == "1":
            sistema.mostrar_medicos()

        elif op == "2":
            paciente = input("Paciente: ")
            nombre_medico = input("Médico: ")
            fecha = input("Fecha (texto): ")
            sistema.registrar_turno(paciente, nombre_medico, fecha)

        elif op == "3":
            sistema.mostrar_turnos()

        elif op == "0":
            print("Fin.")
            break

        else:
            print("Opción inválida.")

menu()